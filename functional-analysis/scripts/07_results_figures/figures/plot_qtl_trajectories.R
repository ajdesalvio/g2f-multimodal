rename_alias <- function(data, target, aliases, description) {
  if (target %in% names(data)) return(data)
  matches <- intersect(aliases, names(data))
  if (length(matches) != 1L) {
    stop(
      description, " must contain '", target, "' or exactly one alias: ",
      paste(aliases, collapse = ", ")
    )
  }
  names(data)[names(data) == matches] <- target
  data
}

require_columns <- function(data, required, description) {
  missing <- setdiff(required, names(data))
  if (length(missing)) {
    stop(description, " is missing: ", paste(missing, collapse = ", "))
  }
  invisible(data)
}

normalize_fpca_type <- function(value) {
  key <- toupper(gsub("[^A-Za-z0-9]", "", value))
  normalized <- case_when(
    key %in% c("DAP", "DAPFPCA", "STANDARD", "STANDARDFPCA") ~ "DAP",
    key %in% c("AGDD", "AGDDFPCA") ~ "AGDD",
    key %in% c("FLOWERINGYIELD", "FLOWERINGYIELDFPCA") ~ "Flowering.Yield",
    is.na(value) ~ NA_character_,
    TRUE ~ NA_character_
  )
  unknown <- unique(value[!is.na(value) & is.na(normalized)])
  if (length(unknown)) {
    stop("Unrecognized FPCA type(s): ", paste(unknown, collapse = ", "))
  }
  normalized
}

