prepare_curves <- function(filename, result_subdir, fpca_type) {
  curves <- fread(
    resolve_input(filename, result_subdir),
    data.table = FALSE
  )
  time_column <- if (fpca_type == "AGDD" && "AGDD" %in% names(curves)) {
    "AGDD"
  } else {
    "DAP"
  }
  require_columns(
    curves,
    c("Pedigree", "Env", "Vegetation.Index", time_column, "Predicted.Value"),
    paste(fpca_type, "predicted-curve table")
  )
  curves <- curves |>
    filter(
      .data$Vegetation.Index == "NGRDI",
      str_detect(.data$Pedigree, "^W10004[^/]*/")
    )
  pedigree_parts <- str_match(curves$Pedigree, "^([^/]+)/([^/]+)")
  if (anyNA(pedigree_parts[, 2L]) || anyNA(pedigree_parts[, 3L])) {
    stop("Could not parse one or more W10004 pedigrees in ", filename)
  }
  curves |>
    mutate(
      Inbred = pedigree_parts[, 2L],
      Tester = pedigree_parts[, 3L],
      FPCA = factor(
        paste(fpca_type, "FPCA"),
        levels = c("DAP FPCA", "AGDD FPCA")
      ),
      Time = .data[[time_column]],
      Join_ID = paste(.data$Env, .data$Tester, .data$FPCA, .data$Inbred, sep = ".")
    )
}

